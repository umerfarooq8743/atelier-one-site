import type { Metadata } from "next";
import { createElement } from "react";
import { siteConfig } from "@/config/site";

interface PageMeta {
  title: string;
  description: string;
  path: string;
  keywords?: string[];
}

/** Unique title, description, canonical, Open Graph and Twitter tags per page. */
export function createMetadata({ title, description, path, keywords }: PageMeta): Metadata {
  return {
    title,
    description,
    keywords,
    alternates: { canonical: path },
    openGraph: { title: `${title} · Atelier One`, description, url: path, type: "website", siteName: siteConfig.name, images: [ogImage] },
    twitter: { card: "summary_large_image", title: `${title} · Atelier One`, description, images: [ogImage.url] },
  };
}

/** Shared social image generated by app/opengraph-image.tsx. */
export const ogImage = { url: "/opengraph-image", width: 1200, height: 630, alt: "Atelier One — Tailoring & Fabric Business Management Software" };

const abs = (path: string) => `${siteConfig.url}${path === "/" ? "" : path}`;

export function organizationJsonLd() {
  return {
    "@context": "https://schema.org",
    "@type": "Organization",
    name: siteConfig.name,
    url: siteConfig.url,
    logo: `${siteConfig.url}/icon.svg`,
    founder: { "@type": "Person", name: siteConfig.owner },
    sameAs: [siteConfig.repository],
    ...(siteConfig.contact.email ? { email: siteConfig.contact.email } : {}),
  };
}

export function websiteJsonLd() {
  return { "@context": "https://schema.org", "@type": "WebSite", name: siteConfig.name, url: siteConfig.url, description: siteConfig.description };
}

export function softwareJsonLd() {
  return {
    "@context": "https://schema.org",
    "@type": "SoftwareApplication",
    name: siteConfig.name,
    applicationCategory: "BusinessApplication",
    applicationSubCategory: "Tailoring and fabric business management",
    operatingSystem: "Web browser",
    description: siteConfig.description,
    url: siteConfig.url,
    author: { "@type": "Person", name: siteConfig.owner },
    featureList: [
      "Customer management", "Garment measurements", "Fabric inventory", "Sale and purchase invoices",
      "Stitching order tracking", "Payments", "Employees, loans and wages", "Expenses", "13 business reports",
      "Role-based access", "Multi-company workspaces",
    ],
  };
}

export function breadcrumbJsonLd(items: { name: string; path: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [{ name: "Home", path: "/" }, ...items].map((it, i) => ({
      "@type": "ListItem", position: i + 1, name: it.name, item: abs(it.path),
    })),
  };
}

export function JsonLd({ data }: { data: object | object[] }) {
  return createElement("script", {
    type: "application/ld+json",
    dangerouslySetInnerHTML: { __html: JSON.stringify(data).replace(/</g, "\\u003c") },
  });
}
